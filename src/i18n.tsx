const dictionaries = { vi, en }

interface I18nContextValue {
  language: Language
  locale: string
  setLanguage: (language: Language) => void
  t: Translator
}

const I18nContext = createContext<I18nContextValue | null>(null)

function getInitialLanguage(): Language {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved === 'vi' || saved === 'en') return saved
  return navigator.language.toLowerCase().startsWith('vi') ? 'vi' : 'en'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage)

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<I18nContextValue>(() => {
    const t: Translator = (key, vars) => {
      let text = dictionaries[language][key] ?? dictionaries.en[key] ?? key
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.replaceAll(`{${name}}`, String(value))
        }
      }
      return text
    }
    return {
      language,
      locale: language === 'vi' ? 'vi-VN' : 'en-US',
      setLanguage: (next) => setLanguageState(next),
      t,
    }
  }, [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside LanguageProvider')
  return value
}

export function categoryDisplayName(category: Category, _t: Translator) {
  return category.name
}

export function questionLabel(questionId: string, t: Translator) {
  return t(`securityQuestion.${questionId}`)
}

export function accountDisplayName(account: Account, _t: Translator) {
  return account.name
}

export function localizeError(error: unknown, t: Translator, fallbackKey: string) {
  if (!(error instanceof Error)) return t(fallbackKey)
  if (error.message.startsWith('error.')) return t(error.message)
  console.error('[O-Wallet]', error)
  return t(fallbackKey)
}
